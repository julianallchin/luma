fn presets_page() -> String {
    let presets = presets();
    let mut out = String::new();
    frontmatter(
        &mut out,
        "Presets",
        "The shipped clip presets, curve shapes, gradients and audio bands.",
    );
    writeln!(out, "Luma ships these presets. A clip preset is a clip graph with a name and a blend mode. Adding one copies its graph into the new clip; the clip does not follow later changes to the preset. **Reads** is the graph's one-line summary, as the timeline shows it.\n").unwrap();
    for output in Kind::ALL.into_iter().filter(|kind| kind.is_output()) {
        let clips: Vec<_> = presets
            .clips
            .iter()
            .filter(|preset| preset.output_kind() == output)
            .collect();
        if clips.is_empty() {
            continue;
        }
        writeln!(out, "## {}\n", output.label()).unwrap();
        writeln!(out, "| Preset | Blend | Reads | Nodes |\n|---|---|---|---|").unwrap();
        for preset in clips {
            let nodes = Kind::ALL
                .into_iter()
                .filter(|kind| preset.graph.nodes.values().any(|node| node.kind == *kind))
                .map(|kind| format!("`{}`", kind.name()))
                .collect::<Vec<_>>()
                .join(", ");
            let name = match &preset.note {
                Some(note) => format!("{} ({note})", preset.name),
                None => preset.name.clone(),
            };
            writeln!(
                out,
                "| {} | {} | {} | {nodes} |",
                cell(&name),
                preset.blend_mode.label(),
                cell(&preset.graph.summary()),
            )
            .unwrap();
        }
        out.push('\n');
    }
    let names = |names: Vec<&str>| {
        names
            .into_iter()
            .map(|name| format!("`{name}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    writeln!(out, "## Curve shapes\n").unwrap();
    writeln!(
        out,
        "A curve's shape chip lists these. In Python, a shape can be one of these names.\n"
    )
    .unwrap();
    writeln!(
        out,
        "{}.\n",
        names(presets.curves.iter().map(|c| c.name.as_str()).collect())
    )
    .unwrap();
    writeln!(out, "## Gradients\n").unwrap();
    writeln!(out, "A color curve's gradient chip lists these. In Python, a gradient can be one of these names.\n").unwrap();
    writeln!(
        out,
        "{}.\n",
        names(presets.gradients.iter().map(|g| g.name.as_str()).collect())
    )
    .unwrap();
    writeln!(out, "## Audio bands\n").unwrap();
    writeln!(out, "An `audio` node's empty band is `low`. In Python, `audio(\"mid\")` reads a band by name.\n").unwrap();
    writeln!(out, "| Band | Low | High |\n|---|---|---|").unwrap();
    for band in &presets.bands {
        writeln!(
            out,
            "| `{}` | {} Hz | {} Hz |",
            band.name,
            num(band.low_hz),
            num(band.high_hz)
        )
        .unwrap();
    }
    out
}

fn meta() -> String {
    let mut pages = vec!["\"index\"".to_string()];
    pages.extend(PAGES.iter().map(|page| format!("\"{}\"", page.slug)));
    pages.push("\"presets\"".into());
    format!(
        "{{\n  \"title\": \"Node Reference\",\n  \"pages\": [\n    {}\n  ]\n}}\n",
        pages.join(",\n    ")
    )
}

fn write(dir: &Path, name: &str, text: &str) {
    let path = dir.join(name);
    std::fs::write(&path, text).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
}

fn main() {
    let covered: Vec<Shown> = PAGES
        .iter()
        .flat_map(|page| page.kinds.iter().copied())
        .collect();
    for shown in Kind::ALL
        .map(Shown::Kind)
        .into_iter()
        .chain([Shown::LiveColor])
    {
        let times = covered.iter().filter(|known| **known == shown).count();
        assert_eq!(times, 1, "{shown:?} is on {times} pages");
    }

    let dir: PathBuf = [
        env!("CARGO_MANIFEST_DIR"),
        "..",
        "..",
        "..",
        "www",
        "content",
        "docs",
        "node-reference",
    ]
    .iter()
    .collect();
    std::fs::create_dir_all(&dir).expect("the node reference directory");

    let mut written = vec!["index.mdx".to_string(), "presets.mdx".to_string()];
    write(&dir, "index.mdx", &index());
    for page in &PAGES {
        let name = format!("{}.mdx", page.slug);
        write(&dir, &name, &self::page(page));
        written.push(name);
    }
    write(&dir, "presets.mdx", &presets_page());
    write(&dir, "meta.json", &meta());

    // Pages this generator no longer writes go.
    for entry in std::fs::read_dir(&dir).expect("the node reference directory") {
        let path = entry.expect("a directory entry").path();
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("");
        if name.ends_with(".mdx") && !written.iter().any(|known| known == name) {
            std::fs::remove_file(&path)
                .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        }
    }
    let dir = dir.canonicalize().unwrap_or(dir);
    println!("wrote {} pages to {}", written.len(), dir.display());
}
