// -- formatting ---------------------------------------------------------------

/// A number as a person writes it: `1`, `0.5`, `−180`.
fn num(value: f64) -> String {
    let text = if value.fract() == 0. && value.abs() < 1e15 {
        format!("{}", value as i64)
    } else {
        format!("{value}")
    };
    text.replace('-', "−")
}

/// Text safe in a Markdown table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// `a`, `a and b`, `a, b and c`.
fn and_list(items: &[String]) -> String {
    match items {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

/// The verb for one name or several.
fn verb(items: &[String], one: &'static str, many: &'static str) -> &'static str {
    if items.len() == 1 {
        one
    } else {
        many
    }
}

fn type_name(ty: InputType) -> &'static str {
    match ty {
        InputType::Number => "number",
        InputType::Vector => "vector",
        InputType::Color => "color",
        InputType::Points => "points",
        InputType::Gradient => "gradient",
        InputType::Heads => "heads",
        InputType::Time => "time",
        InputType::Button => "button",
        InputType::Coordinate => "coordinate",
        InputType::Values => "values",
        InputType::Figures => "figures",
        InputType::Bound => "number or vector",
        InputType::Constant => "number or 3 numbers",
    }
}

fn unit_name(unit: Unit) -> &'static str {
    match unit {
        Unit::Hz => "Hz",
        Unit::Uvz => "u, v, z",
        Unit::Rgb => "RGB",
        other => other.name(),
    }
}

fn unit(def: &InputDef) -> &'static str {
    match (def.ty, def.unit) {
        (InputType::Bound | InputType::Constant, _) => "of what it feeds",
        (_, Some(unit)) => unit_name(unit),
        (_, None) => "",
    }
}

fn range(def: &InputDef) -> String {
    if matches!(def.ty, InputType::Bound | InputType::Constant) {
        return "of what it feeds".into();
    }
    match def.geometry {
        Some(Geometry::Direction) => return "not zero".into(),
        Some(Geometry::Point) => return "0–1 each".into(),
        _ => {}
    }
    let each = if matches!(def.ty, InputType::Vector | InputType::Color) {
        " each"
    } else {
        ""
    };
    match def.range {
        None if matches!(def.ty, InputType::Number | InputType::Vector) => "any".into(),
        None => String::new(),
        Some([Some(min), Some(max)]) if min < 0. => format!("{} to {}{each}", num(min), num(max)),
        Some([Some(min), Some(max)]) => format!("{}–{}{each}", num(min), num(max)),
        Some([Some(min), None]) if def.above_min => format!("above {}", num(min)),
        Some([Some(min), None]) => format!("{} or more", num(min)),
        Some([None, Some(max)]) => format!("{} or less", num(max)),
        Some([None, None]) => "any".into(),
    }
}

fn takes(def: &InputDef) -> &'static str {
    if def.fixed {
        "a whole number"
    } else if def.ty == InputType::Values {
        "a list of numbers and wires"
    } else if def.ty == InputType::Figures {
        "a list of wires"
    } else if def.ty.is_wire_only() {
        "a wire"
    } else if def.ty.is_value_only() {
        "a value"
    } else if def.time_only {
        "a value, or a wire over time"
    } else {
        "a value or a wire"
    }
}

fn gives(shown: Shown) -> String {
    let kind = shown.kind();
    if shown == Shown::LiveColor {
        return "a value: a color".into();
    }
    match shown.node().produces() {
        Produces::Coordinate => "a coordinate".into(),
        Produces::Heads => "heads".into(),
        Produces::Value => "a value: a number, a vector or a color".into(),
        Produces::Figure => "a figure, for a laser's `figures`".into(),
        Produces::Output => {
            let modes = blend_modes(kind)
                .iter()
                .map(|mode| mode.label())
                .collect::<Vec<_>>()
                .join(", ");
            format!("nothing: it is the clip's output. Blend modes: {modes}")
        }
    }
}

