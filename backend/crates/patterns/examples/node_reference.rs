fn frontmatter(out: &mut String, title: &str, description: &str) {
    writeln!(
        out,
        "---\ntitle: {title}\ndescription: \"{description}\"\n---\n\n{HEADER}\n"
    )
    .unwrap();
}

fn kind_section(out: &mut String, shown: Shown) {
    let kind = shown.kind();
    let definition = definition(kind);
    let doc = doc(shown);
    let names: Vec<_> = definition.inputs.iter().map(|(name, _)| *name).collect();
    let documented: Vec<_> = doc.empty.iter().map(|(name, _)| *name).collect();
    assert_eq!(
        names,
        documented,
        "{}: say what each input means when empty, in definition order",
        kind.name()
    );
    for (name, _) in &doc.settings {
        assert!(
            definition.setting(name).is_some(),
            "{}.{name}: no such setting",
            kind.name()
        );
    }

    writeln!(out, "## {}\n", shown.node().label()).unwrap();
    writeln!(
        out,
        "`{}` · Python: `{}` · Gives {}.\n",
        kind.name(),
        doc.python,
        gives(shown)
    )
    .unwrap();
    writeln!(out, "{}\n", doc.about).unwrap();

    if definition.inputs.is_empty() {
        writeln!(out, "No inputs.\n").unwrap();
    } else {
        writeln!(out, "| Input | Type | Unit | Range | Takes | Empty |").unwrap();
        writeln!(out, "|---|---|---|---|---|---|").unwrap();
        for ((name, def), (_, empty)) in definition.inputs.iter().zip(&doc.empty) {
            writeln!(
                out,
                "| `{name}` | {} | {} | {} | {} | {} |",
                type_name(def.ty),
                unit(def),
                range(def),
                takes(def),
                cell(empty),
            )
            .unwrap();
        }
        out.push('\n');
        let listed = |test: &dyn Fn(&InputDef) -> bool| {
            definition
                .inputs
                .iter()
                .filter(|(_, def)| test(def))
                .map(|(name, _)| format!("`{name}`"))
                .collect::<Vec<_>>()
        };
        let grid = definition
            .inputs
            .iter()
            .filter(|(name, _)| grid::on_grid(kind, name))
            .map(|(name, _)| format!("`{name}`"))
            .collect::<Vec<_>>();
        if !grid.is_empty() {
            writeln!(out, "- A number in {} is on the beat grid: a multiple of 1/32 or 1/24 of a beat. The editor snaps a typed number to it. A wire is free.", and_list(&grid)).unwrap();
        }
        let clock = listed(&|def| def.clock);
        if !clock.is_empty() {
            writeln!(out, "- {} {} a clock's period. A wire that follows events gives {} the newest event's value, so the clock keeps its own events. A fader wired in changes the clock's speed as it plays, with no jump: a speed that fits the bar starts where the clock's beats and bars stay on the grid, any other at the next event.", and_list(&clock), verb(&clock, "sets", "set"), verb(&clock, "it", "them")).unwrap();
        }
        let fixed = listed(&|def| def.fixed);
        if !fixed.is_empty() {
            writeln!(
                out,
                "- {} {} the clip's heads, so {} a whole number for the whole clip and {} no wire.",
                and_list(&fixed),
                verb(&fixed, "shapes", "shape"),
                verb(&fixed, "it holds", "they hold"),
                verb(&fixed, "takes", "take")
            )
            .unwrap();
        }
        if !(grid.is_empty() && clock.is_empty() && fixed.is_empty()) {
            out.push('\n');
        }
    }

    if !definition.settings.is_empty() {
        writeln!(out, "| Setting | Options | Default | Notes |").unwrap();
        writeln!(out, "|---|---|---|---|").unwrap();
        for (name, setting) in &definition.settings {
            let options = if setting.options.is_empty() && setting.default.parse::<f64>().is_ok() {
                "a number".to_string()
            } else if setting.options.is_empty() {
                "text".to_string()
            } else {
                setting
                    .options
                    .iter()
                    .map(|option| format!("`{option}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let default = if setting.default.is_empty() {
                "empty".to_string()
            } else {
                format!("`{}`", setting.default)
            };
            let note = doc
                .settings
                .iter()
                .find(|(known, _)| known == name)
                .map_or("", |(_, note)| note);
            writeln!(
                out,
                "| `{name}` | {} | {default} | {} |",
                cell(&options),
                cell(note)
            )
            .unwrap();
        }
        out.push('\n');
    }
}

fn page(page: &Page) -> String {
    let mut out = String::new();
    frontmatter(&mut out, page.title, page.description);
    let intro = page
        .intro
        .replace("{MAX_ELEMENTS}", &MAX_ELEMENTS.to_string());
    writeln!(out, "{intro}\n").unwrap();
    for kind in page.kinds {
        kind_section(&mut out, *kind);
    }
    out
}

fn kinds_from(test: impl Fn(Kind) -> bool) -> String {
    Kind::ALL
        .into_iter()
        .filter(|kind| test(*kind))
        .map(|kind| format!("`{}`", kind.name()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn inputs_of(types: &[InputType]) -> String {
    let mut out = Vec::new();
    for kind in Kind::ALL {
        for (name, def) in &definition(kind).inputs {
            if types.contains(&def.ty) {
                out.push(format!("`{}.{name}`", kind.name()));
            }
        }
    }
    out.join(", ")
}

